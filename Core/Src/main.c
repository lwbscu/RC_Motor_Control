/**
  * @brief  Period elapsed callback in non blocking mode
  * @note   This function is called  when TIM1 interrupt took place, inside
  * HAL_TIM_IRQHandler(). It makes a direct call to HAL_IncTick() to increment
  * a global variable "uwTick" used as application time base.
  * @param  htim : TIM handle
  * @retval None
  */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    /* USER CODE BEGIN Callback 0 */

    /* USER CODE END Callback 0 */
    if (htim->Instance == TIM1) {
        HAL_IncTick();
    }
    /* USER CODE BEGIN Callback 1 */
    // 添加TIM2的处理逻辑
    if (htim->Instance == TIM2) {
        // --- 频率已改为 1000Hz (1ms) ---
        static uint32_t led_counter = 0;
        static uint32_t system_counter = 0;

        system_counter++; // 每1ms增加1

        // LED1快闪 - 每500ms闪烁一次 (500 * 1ms)
        if (++led_counter >= 500) {
            led_counter = 0;
            LED1_TOGGLE();  // LED1快闪，表示程序在运行
        }

        // LED2慢闪 - 每2秒闪烁一次 (2000 * 1ms)
        if (system_counter % 2000 == 0) {
            LED2_TOGGLE();  // LED2慢闪，表示系统正常
        }

        // 电机控制任务 - 以 1000Hz 运行
        MotorControl_Task();

        // VOFA+数据发送 - 每100ms发送一次 (100 * 1ms)
        if (++vofa_send_counter >= 100) {
            vofa_send_counter = 0;
            VOFA_SendData();
        }
    }
    /* USER CODE END Callback 1 */
}

